        const uri =
            LOCAL_POSTER_URIS[strKey] ||
            LOCAL_POSTER_URIS[cleanKey] ||
            LOCAL_POSTER_URIS['real-' + cleanKey] ||
            LOCAL_POSTER_URIS['movie-' + cleanKey] ||
            LOCAL_POSTER_URIS['tv-' + cleanKey] ||
            LOCAL_POSTER_URIS['billboard-' + cleanKey];
        if (uri) return { uri };
